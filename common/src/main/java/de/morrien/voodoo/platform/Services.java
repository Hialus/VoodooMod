package de.morrien.voodoo.platform;

import de.morrien.voodoo.platform.services.IItemFactory;
import de.morrien.voodoo.platform.services.IPlatformHelper;

import java.util.ServiceLoader;

public class Services {
    public static final IPlatformHelper PLATFORM = load(IPlatformHelper.class);
    public static final IItemFactory ITEMS = load(IItemFactory.class);

    public static <T> T load(Class<T> clazz) {
        return ServiceLoader.load(clazz)
                .findFirst()
                .orElseThrow(() -> new NullPointerException("Failed to load service for " + clazz.getName()));
    }
}
